"""Simulated decremental PEEP trial for the site — no patient data.

A 32 x 32 lung (two lobes, the heart cut out, ventral at the top) where every pixel
has its own compliance curve: dependent (dorsal) pixels collapse below a higher
PEEP, non-dependent (ventral) pixels overdistend above a lower one. At constant
tidal volume, the tidal image of each step is the compliance of each pixel times
the driving pressure. The OD/LC curves, the crossing and the per-pixel map are
then computed by Alveo itself (alveo.analysis.odlc.compute_odlc, Costa 2009).

    uv run --project ~/code/guardia/alveo python tools/build_sim.py
"""

import json
from pathlib import Path

import numpy as np

from alveo.analysis.odlc import compute_odlc
from alveo.analysis.peep_trial import PeepStep

N = 32
PEEPS = [20.0, 17.0, 14.0, 11.0, 8.0, 5.0]
VT = 1.0
rng = np.random.default_rng(2809)
yy, xx = np.mgrid[0:N, 0:N].astype(float)


def lobe(cx, cy, rx, ry, k=2.4):
    return (np.abs((xx - cx) / rx) ** k + np.abs((yy - cy) / ry) ** k) <= 1


# Radiological view: the patient's right lung is on the left of the image.
right = lobe(10.0, 16.5, 7.2, 11.5)
left = lobe(22.2, 16.8, 6.4, 11.0)
heart = ((xx - 18.5) / 5.5) ** 2 + ((yy - 13.0) / 5.0) ** 2 <= 1
mask = (right | left) & ~heart
mask[:3] = False
mask[-2:] = False

depth = (yy - 4) / (N - 7)  # 0 ventral -> 1 dorsal
depth = np.clip(depth, 0, 1)
noise = lambda s: rng.normal(0, s, (N, N))
p_close = 2.0 + 13.0 * depth**1.6 + noise(0.9)  # collapse below this PEEP
p_over = 12.5 + 9.0 * depth + noise(1.2)  # overdistension above this PEEP
cmax = (0.75 + 0.5 * depth) * (1 + noise(0.06))


def compliance(peep):
    open_ = 1 / (1 + np.exp(-(peep - p_close) / 1.3))
    soft = 1 / (1 + np.exp((peep - p_over) / 2.2))
    return np.where(mask, cmax * open_ * (0.35 + 0.65 * soft), 0.0)


steps, images = [], []
c_best = max(compliance(p).sum() for p in PEEPS)
for peep in PEEPS:
    c = compliance(peep)
    dp = 10.0 * c_best / c.sum()  # constant tidal volume: 10 cmH2O at the most compliant step
    tidal = c * dp / 10.0
    tidal = np.where(mask, tidal + noise(0.004), 0.0)
    images.append(tidal)
    steps.append(PeepStep(label=f"peep{peep:g}", peep=peep, pplat=round(peep + dp, 1), tidal_image=tidal, source="simulation"))

res = compute_odlc(steps)
best = np.where(res.mask, res.c.best_peep, np.nan)
r = lambda a, d=3: [[None if not np.isfinite(v) else round(float(v), d) for v in row] for row in np.asarray(a, float)]
peak = max(float(np.nanmax(im)) for im in images)
out = {
    "N": N,
    "mask": np.asarray(res.mask, int).tolist(),
    "depth": r(np.where(mask, depth, np.nan), 3),
    "steps": [{"peep": s.peep, "pplat": s.pplat, "tidal": r(im / peak)} for s, im in zip(steps, images)],
    "odlc": {"peeps": [float(x) for x in res.peeps], "od": [round(float(x), 2) for x in res.od_c], "lc": [round(float(x), 2) for x in res.lc_c],
             "best": round(float(res.crossing_c.peep), 2), "value": round(float(res.crossing_c.value), 2)},
    "map": r(best, 1),
}
# a pixel near the front and one near the back, for the compliance chart
for name, (row, col) in {"ventral": (7, 10), "dorsal": (26, 10)}.items():
    out.setdefault("pixels", {})[name] = [round(float(compliance(p)[row, col] / cmax[row, col]), 3) for p in np.arange(4, 22.5, 0.5)]
out["pixel_peeps"] = [float(p) for p in np.arange(4, 22.5, 0.5)]

# a simulated whole-trial impedance curve: 6 steps x 40 s, 20 breaths/min, end-expiratory level falling with PEEP
t = np.arange(0, 6 * 40, 0.1)
k = np.minimum((t // 40).astype(int), 5)
eelv = np.array([1.0, 0.86, 0.72, 0.58, 0.44, 0.33])[k]
amp = np.array([0.18, 0.21, 0.23, 0.22, 0.18, 0.13])[k]
phase = (t * 20 / 60) % 1
breath = np.where(phase < 0.35, np.sin(np.pi / 2 * phase / 0.35), np.exp(-(phase - 0.35) * 6))
wave = eelv + amp * breath + 0.006 * np.sin(t * 0.7)
out["wave"] = {"t": [round(float(x), 1) for x in t[::5]], "z": [round(float(x), 4) for x in wave[::5]], "peep": [PEEPS[i] for i in k[::5]]}

Path(__file__).resolve().parents[1].joinpath("js/data/sim.js").write_text(
    "// Generated by tools/build_sim.py — simulated lung, no patient data.\nexport const SIM = " + json.dumps(out) + ";\n")
print("best PEEP", out["odlc"]["best"], "OD=LC", out["odlc"]["value"])
print("pplat", [s.pplat for s in steps]); print("od", out["odlc"]["od"]); print("lc", out["odlc"]["lc"])
print("map levels", sorted({v for row in out["map"] for v in row if v is not None}), "mask px", int(np.sum(res.mask)))
